import fs from "node:fs";
import vm from "node:vm";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const ctx = { window: {}, console, Date, Math, JSON };
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of ["assets/js/market-data.js", "assets/js/strategies.js", "assets/js/engine.js"]) {
  vm.runInContext(fs.readFileSync(`${root}/${f}`, "utf8"), ctx, { filename: f });
}
const market = ctx.window.ALPHA_MARKET;
const strategies = ctx.window.ALPHA_STRATEGIES;
const Engine = ctx.window.AlphaEngine;

function sample(arr, max = 260) {
  if (arr.length <= max) return arr;
  const out = [];
  for (let i = 0; i < max; i++) out.push(arr[Math.round((i * (arr.length - 1)) / (max - 1))]);
  return out;
}

function round(x, n = 6) {
  if (!Number.isFinite(x)) return 0;
  const p = 10 ** n;
  return Math.round(x * p) / p;
}

function compact(m) {
  const keys = ["total", "cagr", "vol", "sharpe", "sortino", "maxDD", "calmar", "trades", "winRate", "profitFactor", "avgTrade", "expectancy", "bestMonth", "worstMonth", "var95", "benchmarkTotal"];
  const out = {};
  for (const k of keys) out[k] = round(m[k], 6);
  return out;
}

const CAVEATS = {
  "005": "单票样本（NVDA）存在强烈的事后选择与幸存者偏差；结论只用于验证规则，不可外推。",
  "019": "股票池是 2026 年仍然存活的 8 只大盘股，存在幸存者偏差；短期反转在全样本上并未通过。",
  "031": "股票池是 2026 年仍然存活的 8 只大盘股，存在严重幸存者偏差；42% 的年化不是可复制的预期收益。",
  "076": "加密币池只包含 2026 年仍存活的 5 个币，存在严重幸存者偏差；回测收益不可外推。",
  "035": "回测只验证价格动量骨架；ETF 份额/资金流数据未嵌入，实盘需另行接入并做样本外验证。",
};

const results = {};
const rows = [];
for (const s of strategies.filter((x) => x.verification === "backtest")) {
  try {
    const r = Engine.run(s, market, { costBps: s.costBps ?? 2, start: "2017-01-01", end: "2026-11-03" });
    const n = r.dates.length;
    const series = {
      d: sample(r.dates),
      e: sample(r.equity).map((v) => round(v, 5)),
      b: sample(r.benchmark).map((v) => round(v, 5)),
    };
    const fullOk = r.metrics.trades >= 10 && r.metrics.sharpe > 0.2 && r.metrics.cagr > 0;
    const oosOk = r.oosMetrics.trades >= 5 && r.oosMetrics.sharpe >= 0.3 && r.oosMetrics.total > 0;
    const verdict =
      r.oosMetrics.trades < 5
        ? "样本不足"
        : fullOk && oosOk
          ? "样本外通过"
          : oosOk
            ? "仅样本外通过"
            : "样本外未通过";
    results[s.id] = {
      ok: true,
      id: s.id,
      name: s.name,
      start: r.start,
      end: r.end,
      splitDate: r.splitDate,
      metrics: compact(r.metrics),
      is: compact(r.isMetrics),
      oos: compact(r.oosMetrics),
      monthly: r.metrics.months ? r.monthly || [] : [],
      series,
      verdict,
      caveat: CAVEATS[s.id] || null,
      exposure: round(r.exposure, 4),
      turnover: round(r.turnover, 2),
      params: r.params,
      symbols: r.symbols,
      trades: r.trades.slice(-40).map((t) => ({
        entryDate: t.entryDate, exitDate: t.exitDate, side: t.side,
        pnl: round(t.pnl, 5), bars: t.bars,
      })),
      tradeCount: r.trades.length,
      generated: new Date().toISOString(),
    };
    // monthly returns are computed inside metrics; rebuild them here for the heatmap
    const monthly = [];
    const m = new Map();
    for (let i = 0; i < n; i++) {
      const k = r.dates[i].slice(0, 7);
      if (!m.has(k)) m.set(k, { first: r.equity[i], last: r.equity[i] });
      else m.get(k).last = r.equity[i];
    }
    let prev = null;
    for (const [k, v] of m) {
      monthly.push({ month: k, ret: round(prev === null ? v.last / v.first - 1 : v.last / prev - 1, 6) });
      prev = v.last;
    }
    results[s.id].monthly = monthly;
    rows.push({
      id: s.id, name: s.name, cagr: r.metrics.cagr, sharpe: r.metrics.sharpe, dd: r.metrics.maxDD,
      trades: r.metrics.trades, oosCagr: r.oosMetrics.cagr, oosSharpe: r.oosMetrics.sharpe,
      oosTrades: r.oosMetrics.trades, verdict,
    });
    console.log(
      `${s.id} ${s.name.padEnd(22)} CAGR ${(r.metrics.cagr * 100).toFixed(1).padStart(6)}%  ` +
      `Sharpe ${r.metrics.sharpe.toFixed(2).padStart(5)}  DD ${(r.metrics.maxDD * 100).toFixed(0).padStart(4)}%  ` +
      `T ${String(r.metrics.trades).padStart(3)}  OOS ${(r.oosMetrics.cagr * 100).toFixed(1).padStart(6)}%  ` +
      `Sh ${r.oosMetrics.sharpe.toFixed(2).padStart(5)}  ${verdict}`
    );
  } catch (e) {
    results[s.id] = { ok: false, id: s.id, name: s.name, error: String(e.message || e) };
    console.error(`${s.id} ${s.name} FAILED: ${e.stack || e.message}`);
  }
}

const meta = {
  generated: new Date().toISOString(),
  dataStart: market.dates[0],
  dataEnd: market.dates[market.dates.length - 1],
  strategies: Object.keys(results).length,
  source: market.meta.source,
  split: "70% 样本内 / 30% 样本外，按时间顺序",
  costs: "单边 2–5 bps，按策略设置；不含融资/借券/税",
  disclaimer: "历史回测仅用于验证规则可执行性与风险特征，不代表未来收益。",
};
const out = "/* generated by scripts/build_results.mjs; do not edit by hand */\nwindow.ALPHA_RESULTS = "
  + JSON.stringify({ meta, byId: results }, null, 0) + ";\n";
const target = `${root}/assets/js/results.js`;
fs.writeFileSync(target, out);
console.log(`\nwrote ${target} (${(fs.statSync(target).size / 1024).toFixed(0)} KB)`);
const failed = rows.filter((r) => r.verdict !== "样本外通过");
console.log(`pass ${rows.length - failed.length}/${rows.length}`);
