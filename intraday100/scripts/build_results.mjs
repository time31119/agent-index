import fs from "node:fs";
import vm from "node:vm";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const ctx = { window: {}, console, Date, Math, JSON };
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of ["assets/js/intraday-data.js", "assets/js/strategies.js", "assets/js/engine.js"]) {
  vm.runInContext(fs.readFileSync(`${root}/${f}`, "utf8"), ctx, { filename: f });
}
const DATA = ctx.window.INTRADAY_DATA;
const strategies = ctx.window.INTRADAY_STRATEGIES;
const E = ctx.window.IntradayEngine;

const round = (x, n = 6) => (Number.isFinite(x) ? Math.round(x * 10 ** n) / 10 ** n : x === Infinity ? null : 0);
function compact(m) {
  const keys = ["total", "cagr", "sharpe", "dailySharpe", "maxDD", "trades", "winRate", "profitFactor", "avgTrade", "activeDays", "greenDays", "redDays", "greenDayRate", "avgDaily", "bestDay", "worstDay", "maxLosingStreak", "overnight", "avgBars"];
  const out = {};
  for (const k of keys) out[k] = round(m[k], 6);
  return out;
}
function sample(arr, max = 240) {
  if (arr.length <= max) return arr;
  const out = [];
  for (let i = 0; i < max; i++) out.push(arr[Math.round((i * (arr.length - 1)) / (max - 1))]);
  return out;
}

const results = {};
const rows = [];
for (const s of strategies.filter((x) => x.verification === "backtest")) {
  try {
    const r = E.run(s, s.dataset, { costBps: s.costBps ?? 2 });
    const m = r.metrics;
    const trades = r.trades.map((t) => ({
      entryDate: t.entryDate, exitDate: t.exitDate, entryTime: t.entryTime, exitTime: t.exitTime,
      side: t.side, pnl: round(t.pnl, 6), bars: t.bars, reason: t.reason,
    }));
    results[s.id] = {
      ok: true,
      id: s.id,
      dataset: s.dataset,
      start: r.start,
      end: r.end,
      splitDate: r.splitDate,
      metrics: compact(m),
      is: compact(r.is),
      oos: compact(r.oos),
      verdict: r.verdict,
      noOvernight: r.noOvernight,
      equity: sample(r.equity.map((e) => ({ date: e.date, v: round(e.v, 5) }))),
      days: r.days.map((d) => ({ date: d.date, pnl: round(d.pnl, 6) })),
      trades: trades.slice(-80),
      tradeCount: trades.length,
      best: r.best ? { entryDate: r.best.entryDate, exitDate: r.best.exitDate, entryTime: r.best.entryTime, exitTime: r.best.exitTime, side: r.best.side, pnl: round(r.best.pnl, 6), reason: r.best.reason } : null,
      worst: r.worst ? { entryDate: r.worst.entryDate, exitDate: r.worst.exitDate, entryTime: r.worst.entryTime, exitTime: r.worst.exitTime, side: r.worst.side, pnl: round(r.worst.pnl, 6), reason: r.worst.reason } : null,
      params: r.params || s.params,
      generated: new Date().toISOString(),
    };
    rows.push({ id: s.id, name: s.name, T: m.trades, green: m.greenDayRate, ls: m.maxLosingStreak, cagr: m.cagr, dd: m.maxDD, oos: r.oos.cagr, verdict: r.verdict });
    console.log(`${s.id} ${s.name.padEnd(20)} T${String(m.trades).padStart(4)} green ${(m.greenDayRate * 100).toFixed(0).padStart(3)}% LS${String(m.maxLosingStreak).padStart(2)} total ${(m.total * 100).toFixed(1).padStart(6)}% DD ${(m.maxDD * 100).toFixed(1).padStart(6)}% OOS ${r.oos.cagr == null ? "—" : (r.oos.cagr * 100).toFixed(1)}% ${r.verdict}`);
  } catch (e) {
    results[s.id] = { ok: false, id: s.id, error: String(e.message || e) };
    console.error(`${s.id} ${s.name} FAILED: ${e.stack || e.message}`);
  }
}

const meta = {
  generated: new Date().toISOString(),
  source: "Yahoo Finance intraday bars",
  datasets: Object.fromEntries(Object.entries(DATA.datasets).map(([k, d]) => [k, d.meta])),
  split: "70% 时间样本内 / 30% 样本外",
  costs: "单边 2–4 bps，按策略设置；不含融资/借券/税/冲击",
  disclaimer: "没有任何策略能保证每天盈利；绿天率只是历史统计，不是承诺。",
};
fs.writeFileSync(`${root}/assets/js/results.js`, "/* generated by scripts/build_results.mjs */\nwindow.INTRADAY_RESULTS = " + JSON.stringify({ meta, byId: results }) + ";\n");
console.log(`\nwrote results.js; pass ${rows.filter((r) => r.verdict === "样本外通过").length}/${rows.length}`);
