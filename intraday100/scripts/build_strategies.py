#!/usr/bin/env python3
"""Build and validate the 100 intraday dossiers."""
from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from data.batch1 import STRATEGIES as B1  # noqa: E402
from data.batch2 import STRATEGIES as B2  # noqa: E402
from data.batch3 import STRATEGIES as B3  # noqa: E402
from data.batch4 import STRATEGIES as B4  # noqa: E402
from data.batch5 import STRATEGIES as B5  # noqa: E402
from data.common import FAMILIES  # noqa: E402

STRATEGIES = B1 + B2 + B3 + B4 + B5

REQUIRED = [
    "id", "code", "slug", "name", "en", "familyCode", "family", "market", "session",
    "holding", "direction", "edge", "aiRole", "ai", "thesis", "setup", "entry", "exit",
    "risk", "data", "execution", "fails", "liveCheck", "verification", "riskLevel",
    "capital", "access", "capacity", "readiness", "tags", "caseStudy",
]
ENGINES = {
    "orb", "opening_drive", "gap_continuation", "gap_fade", "prev_day_break",
    "vwap_reversion", "bollinger_scalp", "rsi_reversion", "drop_reversal",
    "opening_fade", "intraday_momentum", "late_momentum", "relative_momentum",
    "volume_ignition", "pairs",
}
DATASETS = {"five", "hour", "crypto"}
VERIFICATIONS = {"backtest", "paper", "data", "audit"}
RISKS = {"低", "中", "中高", "高", "极高"}


def validate() -> None:
    errors = []
    if len(STRATEGIES) != 100:
        errors.append(f"expected 100, got {len(STRATEGIES)}")
    ids = [s["id"] for s in STRATEGIES]
    if ids != [f"{i:03d}" for i in range(1, 101)]:
        errors.append("ids must be 001..100 in order")
    slugs = [s["slug"] for s in STRATEGIES]
    if len(set(slugs)) != len(slugs): errors.append("duplicate slugs")
    counts = Counter(s["familyCode"] for s in STRATEGIES)
    if any(counts.get(k, 0) != 10 for k in FAMILIES): errors.append(f"family counts {dict(counts)}")
    for s in STRATEGIES:
        for key in REQUIRED:
            value = s.get(key)
            if value is None or value == "" or (isinstance(value, list) and not value):
                errors.append(f"{s['id']} missing {key}")
        if s["verification"] not in VERIFICATIONS: errors.append(f"{s['id']} verification")
        if s["riskLevel"] not in RISKS: errors.append(f"{s['id']} risk")
        if not isinstance(s["readiness"], int) or not 0 <= s["readiness"] <= 100: errors.append(f"{s['id']} readiness")
        if s["family"] != FAMILIES.get(s["familyCode"]): errors.append(f"{s['id']} family")
        if s["verification"] == "backtest":
            if s["engine"] not in ENGINES: errors.append(f"{s['id']} engine {s['engine']}")
            if s["dataset"] not in DATASETS: errors.append(f"{s['id']} dataset {s['dataset']}")
            if not s.get("params"): errors.append(f"{s['id']} params")
            if not s.get("symbols"): errors.append(f"{s['id']} symbols")
    if errors:
        print("VALIDATION FAILED")
        for e in errors: print(" -", e)
        raise SystemExit(1)
    c = Counter(s["verification"] for s in STRATEGIES)
    print(f"validated {len(STRATEGIES)} | backtest={c['backtest']} paper={c['paper']} data={c['data']} audit={c['audit']}")


def clean(s: dict) -> dict:
    order = [
        "id", "code", "slug", "name", "en", "familyCode", "family", "market", "symbols",
        "session", "holding", "direction", "edge", "aiRole", "ai", "thesis", "setup",
        "entry", "exit", "risk", "data", "execution", "fails", "liveCheck", "protocol",
        "verification", "engine", "params", "dataset", "benchmark", "riskLevel", "capital",
        "access", "capacity", "readiness", "costBps", "tags", "caseStudy", "caseType",
    ]
    return {k: s[k] for k in order if k in s}


def main() -> None:
    validate()
    strategies = [clean(s) for s in STRATEGIES]
    counts = Counter(s["verification"] for s in strategies)
    meta = {
        "title": "INTRADAY 100",
        "subtitle": "100 条只做日内、不留隔夜的 AI 交易策略",
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "families": [{"code": k, "name": v, "count": sum(1 for s in strategies if s["familyCode"] == k)} for k, v in FAMILIES.items()],
        "counts": {"total": len(strategies), **{k: counts[k] for k in ("backtest", "paper", "data", "audit")}},
        "disclaimer": "没有任何日内策略能保证每天盈利。本站用绿天率、最大连亏与最差单日揭示风险；历史回测不代表未来收益。",
    }
    out = ROOT / "assets" / "js" / "strategies.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "/* generated by scripts/build_strategies.py */\nwindow.INTRADAY_META = " + json.dumps(meta, ensure_ascii=False, separators=(",", ":")) + ";\n"
    text += "window.INTRADAY_STRATEGIES = " + json.dumps(strategies, ensure_ascii=False, separators=(",", ":")) + ";\n"
    out.write_text(text, encoding="utf-8")
    jout = ROOT / "data" / "strategies.json"
    jout.parent.mkdir(parents=True, exist_ok=True)
    jout.write_text(json.dumps({"meta": meta, "strategies": strategies}, ensure_ascii=False, indent=2), encoding="utf-8")
    csvout = ROOT / "data" / "intraday-index.csv"
    with csvout.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["编号", "家族", "名称", "市场", "时段", "持有", "方向", "AI 用法", "验证", "风险", "就绪度", "逻辑"])
        for s in strategies:
            w.writerow([s["id"], s["family"], s["name"], s["market"], s["session"], s["holding"], s["direction"], s["aiRole"], s["verification"], s["riskLevel"], s["readiness"], s["thesis"]])
    print(f"wrote {out} ({out.stat().st_size/1024:.0f} KB)")
    print(f"wrote {jout} ({jout.stat().st_size/1024:.0f} KB)")
    print(f"wrote {csvout}")


if __name__ == "__main__":
    main()
